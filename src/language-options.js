export const curatedCodes = new Set(['en', 'hi', 'pa', 'ur'])
export const featuredCodes = ['en', 'hi', 'pa', 'ur', 'gu', 'bn']
const rtlCodes = new Set(['ar', 'ckb', 'dv', 'fa', 'he', 'ps', 'sd', 'ug', 'ur', 'yi'])

export const globalLanguages = languageRows.map(([code, name, native]) => ({
  code,
  name,
  native,
  short: code.slice(0, 2).toUpperCase(),
  curated: curatedCodes.has(code),
  rtl: rtlCodes.has(code),
}))

export const featuredLanguages = featuredCodes.map((code) => globalLanguages.find((language) => language.code === code))
export const googleLanguageCodes = globalLanguages.map((language) => language.code).filter((code) => code !== 'en').join(',')
